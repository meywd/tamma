    {
        var changes = new List<GitHubFileChange>
        {
            new() { FilePath = "a.cs", ChangeType = "added", Additions = 50, Deletions = 0 },
            new() { FilePath = "b.cs", ChangeType = "modified", Additions = 10, Deletions = 5 },
