    private static Mock<IGitHubIntegrationService> NoExistingPr()
    {
        var gh = new Mock<IGitHubIntegrationService>();
        gh.Setup(g => g.GetGitHubOpenPullRequestForBranchAsync(It.IsAny<string>(), It.IsAny<string>(), It.IsAny<string>()))
